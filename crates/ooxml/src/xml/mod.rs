//! Лексер и pull-парсер XML с абсолютной лексической сохранностью.
//!
//! # Почему не «просто XML-парсер»
//!
//! Замеры корпуса из 43 реальных файлов (798 XML-частей) показали, что
//! каноникализации XML в природе не существует. В одном и том же корпусе
//! сосуществуют:
//!
//! * две формы декларации — со `standalone` (351 часть) и без него (71);
//! * BOM в 16 частях (только `.docx`) и его отсутствие во всех `.xlsx`;
//! * CRLF в 410 частях, причём у Office сразу после декларации идёт `\r\n`;
//! * `&quot;` (121) **и** `&#34;` (44); `&gt;` (2) **и** `&#62;` (3); плюс
//!   `&#xA;` (144), `&amp;` (83), `&#60;` (3), `&#160;` (1);
//! * `<a />` с пробелом перед `/>`;
//! * ни одной части, оканчивающейся переводом строки, — все 798 кончаются `>`.
//!
//! Любая нормализация — «привести кавычки к одной форме», «убрать лишний
//! пробел», «дописать перевод строки» — меняет байты файла, который никто не
//! правил. Поэтому:
//!
//! 1. [`lexer`] выдаёт события, спаны которых **плитуют вход без дыр и
//!    наложений**; конкатенация спанов побайтово равна исходнику
//!    ([`lexer::retile`]).
//! 2. Текст и значения атрибутов не декодируются при разборе. Декодирование —
//!    [`entity`], лениво, и только для типизированного API.
//! 3. [`escape`] экранирует **исключительно новое** содержимое.
//!
//! # Безопасность
//!
//! `<!DOCTYPE` отвергается безусловно ([`crate::error::XmlError::DoctypeForbidden`]):
//! это вектор XXE и billion-laughs, и настраиваемым такой запрет быть не может.
//! Раз DTD нет — нет и пользовательских сущностей, поэтому [`entity`] знает
//! ровно пять предопределённых плюс числовые ссылки. Глубина, число атрибутов и
//! число узлов ограничены [`crate::Limits`] и проверяются до работы над узлом, а
//! не после.

pub mod entity;
pub mod escape;
pub mod lexer;
pub mod name;
pub mod ns;
pub mod reader;

pub use entity::{decode_attr, decode_text};
pub use escape::{escape_attr, escape_text};
pub use lexer::{Event, Lexer, RawAttr, retile};
pub use name::QName;
pub use ns::{Namespaces, NsUri};
pub use reader::Reader;
