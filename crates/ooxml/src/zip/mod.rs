//! Разбор ZIP-контейнера с сохранением всех полей обоих заголовков.
//!
//! # Зачем это отдельный слой, а не «взять готовый zip-крейт»
//!
//! Крейты общего назначения моделируют ZIP как «список файлов с
//! содержимым». Такая модель теряет всё, что не влияет на распаковку:
//! вендорские extra-поля, различия между локальным заголовком и каталогом,
//! выравнивающие дыры, форму data descriptor'а. Для нашей задачи —
//! «открыть чужой файл, поменять одну ячейку, сохранить и не потерять
//! ничего» — теряется ровно то, ради чего всё затевалось.
//!
//! Здесь модель другая: [`RawEntry`] — это не «файл», а **описание байт**.
//! Каждое поле соответствует конкретному участку входа, а сжатые данные
//! представлены спаном, который копируется как есть и никогда не
//! перепаковывается.
//!
//! # Измеренные факты корпуса, которые определили модель
//!
//! 43 реальных файла, ~850 записей, три producer'а:
//!
//! * область extra **локального** заголовка у MS Office — 520 байт
//!   (`0xA220`, Open Packaging Growth Hint), а extra той же записи в
//!   **каталоге** — 0 байт. Отсюда раздельные [`RawEntry::local_extra`] и
//!   [`RawEntry::cd_extra`]: writer, копирующий одно в другое, разойдётся с
//!   оригиналом на первой же записи;
//! * `version made by` принимает значения 20, 23, 45 и 788 (`0x0314` — ZIP 2.0
//!   на Unix-хосте) — то есть это не константа, а данные;
//! * метод 0 (stored) встречается наравне с 8, каталожные записи (имя на `/`)
//!   тоже;
//! * Google Sheets и LibreOffice пишут потоком: bit 3, нулевые crc и размеры
//!   в локальном заголовке, дескриптор `PK\x07\x08` + 3×u32 за данными;
//! * zip64 не встречается ни разу, но поддержан: вход недоверенный.
//!
//! # Порядок записей
//!
//! [`ZipArchive::entries`] идёт в порядке центрального каталога,
//! [`ZipArchive::order_by_offset`] — в физическом. В корпусе они совпадают,
//! но формат этого не требует, и код нигде на совпадение не опирается.

