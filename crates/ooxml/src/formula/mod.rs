//! Разбор формул Excel в дерево, печать обратно и правка ссылок.
//!
//! # Чего здесь нет и не будет: вычислений
//!
//! Этот модуль **не считает формулы**. Решение сознательное, а не отложенное.
//! Полноценный движок — это граф зависимостей с обнаружением циклов и порядком
//! обхода, массивные формулы с неявным расширением, четыреста с лишним функций,
//! арифметика Excel с её собственными правилами округления и дат — включая
//! знаменитое несуществующее 29 февраля 1900 года, которое приходится
//! воспроизводить ради совместимости. По объёму это отдельный проект размером
//! со всё остальное ядро, и половина его не даёт ничего для главной цели —
//! сохранности чужого документа.
//!
//! Значения ячеек берутся из кэша `<v>`, который Excel записал сам. При
//! структурной правке выставляется `fullCalcOnLoad`, и пересчёт делает Excel
//! при открытии файла.
//!
//! # Тогда зачем разбор
//!
//! Ровно ради двух вещей, обе — про сохранность:
//!
//! 1. **Сдвиг ссылок.** Вставка строки над `=SUM(A5:A9)` обязана дать
//!    `=SUM(A6:A10)`. Без разбора любая структурная правка тихо ломает каждую
//!    формулу файла — «тихо» здесь ключевое: файл откроется, формулы будут
//!    выглядеть правдоподобно, а считать не то.
//! 2. **Анализ зависимостей.** Какие ячейки читает формула — [`dependencies`].
//!
//! # Две операции над ссылками, которые нельзя путать
//!
//! * [`shift_refs`] — структурная правка листа. `$` **не защищает**: после
//!   вставки строки `$A$5` становится `$A$6`.
//! * [`translate_refs`] — перенос формулы в другую ячейку (копирование,
//!   заполнение). Здесь `$` работает как ожидается.
//!
//! Подробности и обоснование — в [`Reference::shift`] и [`Reference::translate`].
//!
//! # Точность круга
//!
//! `print(parse(x)) == x` — не пожелание, а проверяемый инвариант: на формулах
//! реального корпуса он держится побайтово, включая пробелы, переводы строк
//! внутри формулы и написание чисел. Как это устроено — в доке [`Expr`].
//!
//! # Пример
//!
//! ```
//! use ooxml::formula::{Shift, dependencies, parse_formula, print_formula, shift_refs};
//!
//! let mut e = parse_formula("SUM(A5:A9)*$B$2")?;
//! assert_eq!(print_formula(&e), "SUM(A5:A9)*$B$2");
//! assert_eq!(dependencies(&e).len(), 2);
//!
//! // Вставили строку на позицию 0 (перед первой строкой листа).
//! shift_refs(&mut e, &Shift::insert_rows(0, 1));
//! assert_eq!(print_formula(&e), "SUM(A6:A10)*$B$3");
//! # Ok::<(), ooxml::Error>(())
//! ```

