use crate::error::Result;

/// Разбирает формулу в дерево.
///
/// Текст подаётся **без ведущего `=`** — именно так формулы лежат в элементе
/// `<f>` листа и в `<definedName>` книги.
///
/// # Ошибки
///
/// [`crate::error::FormulaError`] с позицией в тексте: незакрытая скобка или
/// кавычка, неожиданный символ, слишком глубокая вложенность ([`MAX_DEPTH`]).
pub fn parse_formula(src: &str) -> Result<Expr> {
    parser::parse(src)
}

/// Печатает дерево обратно в текст формулы (без ведущего `=`).
#[must_use]
pub fn print_formula(e: &Expr) -> String {
    print::print(e)
}

/// Сдвигает ссылки после вставки или удаления строк (столбцов).
///
/// Возвращает число изменённых ссылок. Ссылки, попавшие в удалённый диапазон,
/// становятся `#REF!` — ровно как в Excel.
///
/// Абсолютность (`$`) на результат **не влияет**: при структурной правке едут
/// и абсолютные ссылки тоже. Обоснование — в [`Reference::shift`].
pub fn shift_refs(e: &mut Expr, sh: &Shift<'_>) -> usize {
    let mut n = 0usize;
    e.visit_refs_mut(&mut |r| {
        if r.shift(sh) {
            n = n.saturating_add(1);
        }
    });
    n
}

/// Переносит формулу в другую ячейку: относительные части ссылок смещаются на
/// `d_col`/`d_row`, абсолютные остаются на месте.
///
/// Это операция копирования и заполнения, а не структурной правки. Возвращает
/// число изменённых ссылок.
pub fn translate_refs(e: &mut Expr, d_col: i64, d_row: i64) -> usize {
    let mut n = 0usize;
    e.visit_refs_mut(&mut |r| {
        if r.translate(d_col, d_row) {
            n = n.saturating_add(1);
        }
    });
    n
}

/// Собирает все ссылки формулы в порядке появления.
///
/// Повторы не устраняются: `A1+A1` даёт две ссылки. Кто строит граф
/// зависимостей, тот и решает, нужна ли ему дедупликация.
#[must_use]
pub fn dependencies(e: &Expr) -> Vec<Reference> {
    let mut out = Vec::new();
    e.visit_refs(&mut |r| out.push(r.clone()));
    out
}

/// Собирает имена всех вызываемых функций в порядке появления.
///
/// Префикс `_xlfn.` не снимается: он часть имени, записанного в файле.
#[must_use]
pub fn functions(e: &Expr) -> Vec<String> {
    let mut out = Vec::new();
    e.walk(&mut |n| {
        if let ExprKind::Func { name, .. } = &n.kind {
            out.push(name.to_string());
        }
    });
    out
}
