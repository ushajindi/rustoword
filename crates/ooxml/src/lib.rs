//! Ядро для работы с файлами OOXML (`.xlsx`, `.docx`).
//!
//! # Центральная гипотеза
//!
//! Правка чужого документа не должна ничего разрушать. Реальный `.docx` содержит
//! сотни элементов спецификации ECMA-376 плюс вендорские расширения; смоделировать
//! их все невозможно. Библиотеки, построенные на полной типизированной модели,
//! теряют при сохранении всё, чего не знают — ревизии, комментарии, нумерацию,
//! макросы.
//!
//! Здесь применяется двухуровневая модель сохранности:
//!
//! 1. **Нетронутые части пакета копируются побайтово** — вместе с сжатыми данными
//!    и обоими ZIP-заголовками. Они никогда не распаковываются и не перепаковываются.
//! 2. **Тронутые XML-части живут в preserving DOM** — дереве, которое хранит
//!    неизвестные элементы, атрибуты, их порядок, пробелы и стиль экранирования
//!    ровно так, как они лежали в исходнике.
//!
//! Типизированный API (лист, ячейка, абзац) — это фасад над таким деревом, а не
//! замена ему. Модель наращивается постепенно, и на каждом шаге сохранность полная.
//!
//! # Ограничения окружения
//!
//! Крейт не имеет зависимостей и не обращается к файловой системе, сети и часам —
//! работа идёт с `&[u8]`. Это делает его пригодным для `wasm32-unknown-unknown`
//! и проверяется тестами `no_deps.rs` и `no_fs.rs`.
//!
//! # Недоверенный вход
//!
//! Любой публичный вход считается враждебным. Квоты задаются через [`Limits`];
//! значения по умолчанию рассчитаны на файлы до ~50 МБ. Внешние сущности и DOCTYPE
//! запрещены безусловно, коэффициент сжатия проверяется инкрементально **внутри**
//! цикла распаковки, а не по заголовку, который может врать.

